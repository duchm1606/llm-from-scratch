/*
 * Generates src/unicode_tables.h: the character classes used by the GPT-2
 * pre-tokenizer regex (\p{L}, \p{N}, \s) as sorted codepoint ranges.
 *
 * Usage: gen_unicode_tables UnicodeData.txt VERSION > src/unicode_tables.h
 * `make unicode-tables` downloads UnicodeData.txt and runs this.
 */
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#define NUM_CODEPOINTS 0x110000

typedef struct {
    uint32_t lo, hi;
} Range;

/*
 * \s in the Rust regex engine used by tiktoken is the Unicode White_Space
 * property, which lives in PropList.txt rather than UnicodeData.txt. It is a
 * short, stable list, so it is spelled out here.
 */
static const Range white_space[] = {
    {0x0009, 0x000D}, {0x0020, 0x0020}, {0x0085, 0x0085}, {0x00A0, 0x00A0},
    {0x1680, 0x1680}, {0x2000, 0x200A}, {0x2028, 0x2029}, {0x202F, 0x202F},
    {0x205F, 0x205F}, {0x3000, 0x3000},
};

/* General category initial ('L' for letters, 'N' for numbers, ...) of every
 * codepoint; 0 for unassigned ones. */
static char category[NUM_CODEPOINTS];

/* Field i (0-based) of a semicolon-separated line, or NULL. */
static const char *field(const char *line, int i)
{
    while (i-- > 0) {
        line = strchr(line, ';');
        if (!line)
            return NULL;
        line++;
    }
    return line;
}

/* Whether the name field (which runs up to the next ';') ends with suffix. */
static int name_ends_with(const char *name, const char *suffix)
{
    size_t n = strcspn(name, ";"), k = strlen(suffix);
    return n >= k && memcmp(name + n - k, suffix, k) == 0;
}

/* Fills category[] from UnicodeData.txt. Large blocks such as CJK ideographs
 * are listed as a "<..., First>" line followed by a "<..., Last>" line. */
static int load_categories(const char *path)
{
    FILE *f = fopen(path, "r");
    if (!f) {
        perror(path);
        return 0;
    }
    char line[1024];
    long first = -1, lines = 0;
    while (fgets(line, sizeof line, f)) {
        const char *name = field(line, 1);
        const char *cat = field(line, 2);
        char *end;
        unsigned long cp = strtoul(line, &end, 16);
        if (!name || !cat || end == line || *end != ';' || cp >= NUM_CODEPOINTS) {
            fprintf(stderr, "%s:%ld: malformed line\n", path, lines + 1);
            fclose(f);
            return 0;
        }
        category[cp] = cat[0];
        if (name_ends_with(name, ", First>")) {
            first = (long)cp;
        } else if (first >= 0 && name_ends_with(name, ", Last>")) {
            for (unsigned long c = (unsigned long)first; c <= cp; c++)
                category[c] = cat[0];
            first = -1;
        }
        lines++;
    }
    fclose(f);
    if (lines == 0) {
        fprintf(stderr, "%s: no data\n", path);
        return 0;
    }
    return 1;
}

static void emit(const char *name, const Range *ranges, size_t n)
{
    printf("static const CodepointRange %s[] = {\n", name);
    for (size_t i = 0; i < n; i++)
        printf("    {0x%05X, 0x%05X},\n", (unsigned)ranges[i].lo, (unsigned)ranges[i].hi);
    printf("};\n\n");
}

/* Emits the maximal runs of codepoints whose category starts with initial. */
static int emit_category(const char *name, char initial)
{
    static Range ranges[NUM_CODEPOINTS / 2 + 1];
    size_t n = 0;
    for (uint32_t cp = 0; cp < NUM_CODEPOINTS; cp++) {
        if (category[cp] != initial)
            continue;
        if (n > 0 && ranges[n - 1].hi == cp - 1)
            ranges[n - 1].hi = cp;
        else
            ranges[n++] = (Range){cp, cp};
    }
    if (n == 0) {
        fprintf(stderr, "no codepoints in category %c\n", initial);
        return 0;
    }
    emit(name, ranges, n);
    return 1;
}

int main(int argc, char **argv)
{
    if (argc != 3) {
        fprintf(stderr, "usage: %s UnicodeData.txt VERSION\n", argv[0]);
        return 2;
    }
    if (!load_categories(argv[1]))
        return 1;

    printf("/* Generated by tools/gen_unicode_tables.c from Unicode %s. Do not edit. */\n", argv[2]);
    printf("#ifndef LLM_UNICODE_TABLES_H\n#define LLM_UNICODE_TABLES_H\n\n");
    printf("#include <stdint.h>\n\n");
    printf("typedef struct {\n    uint32_t lo, hi;\n} CodepointRange;\n\n");
    emit("unicode_white_space", white_space, sizeof white_space / sizeof white_space[0]);
    if (!emit_category("unicode_letters", 'L') || !emit_category("unicode_numbers", 'N'))
        return 1;
    printf("#endif\n");
    return 0;
}
