#!/usr/bin/env python3
"""Generate src/unicode_tables.h: the character classes used by the GPT-2
pre-tokenizer regex (\\p{L}, \\p{N}, \\s) as sorted codepoint ranges.

Usage: python3 tools/gen_unicode_tables.py > src/unicode_tables.h
"""
import sys
import unicodedata

# \s in the Rust regex engine used by tiktoken is the Unicode White_Space
# property. Python has no query for it, and str.isspace() differs (it includes
# U+001C..U+001F), so the list is spelled out here.
WHITE_SPACE = [
    (0x0009, 0x000D), (0x0020, 0x0020), (0x0085, 0x0085), (0x00A0, 0x00A0),
    (0x1680, 0x1680), (0x2000, 0x200A), (0x2028, 0x2029), (0x202F, 0x202F),
    (0x205F, 0x205F), (0x3000, 0x3000),
]


def ranges(pred):
    out = []
    for cp in range(0x110000):
        if not pred(cp):
            continue
        if out and out[-1][1] == cp - 1:
            out[-1][1] = cp
        else:
            out.append([cp, cp])
    return out


def emit(name, rs):
    print(f"static const CodepointRange {name}[] = {{")
    for lo, hi in rs:
        print(f"    {{0x{lo:05X}, 0x{hi:05X}}},")
    print("};\n")


def main():
    letters = ranges(lambda cp: unicodedata.category(chr(cp)).startswith("L"))
    numbers = ranges(lambda cp: unicodedata.category(chr(cp)).startswith("N"))

    print(f"/* Generated by tools/gen_unicode_tables.py from Unicode "
          f"{unicodedata.unidata_version}. Do not edit. */")
    print("#ifndef LLM_UNICODE_TABLES_H")
    print("#define LLM_UNICODE_TABLES_H\n")
    print("#include <stdint.h>\n")
    print("typedef struct {\n    uint32_t lo, hi;\n} CodepointRange;\n")
    emit("unicode_white_space", WHITE_SPACE)
    emit("unicode_letters", letters)
    emit("unicode_numbers", numbers)
    print("#endif")


if __name__ == "__main__":
    sys.exit(main())
